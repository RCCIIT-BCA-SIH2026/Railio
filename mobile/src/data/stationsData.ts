/**
 * Fast search utility for stations
 * Prioritizes:
 * 1. Exact station code match
 * 2. Prefix code match (e.g. 'SD' -> 'SDAH')
 * 3. Prefix name match (e.g. 'Seal' -> 'Sealdah')
 * 4. Substring in code / name / city / state / aliases
 */
export const searchStations = (query: string, limit: number = 25): StationItem[] => {
  if (!query || query.trim().length === 0) {
    // Return popular stations by default
    return ALL_INDIAN_STATIONS.filter((s) => s.isPopular).slice(0, limit);
  }

  const q = query.trim().toLowerCase();
  const exactCodeMatches: StationItem[] = [];
  const codePrefixMatches: StationItem[] = [];
  const namePrefixMatches: StationItem[] = [];
  const cityPrefixMatches: StationItem[] = [];
  const otherMatches: StationItem[] = [];

  for (const s of ALL_INDIAN_STATIONS) {
    const codeLower = s.code.toLowerCase();
    const nameLower = s.name.toLowerCase();
    const cityLower = s.city.toLowerCase();
    const stateLower = s.state.toLowerCase();
    const aliasMatch = s.aliases?.some((a) => a.toLowerCase().includes(q));

    if (codeLower === q) {
      exactCodeMatches.push(s);
    } else if (codeLower.startsWith(q)) {
      codePrefixMatches.push(s);
    } else if (nameLower.startsWith(q)) {
      namePrefixMatches.push(s);
    } else if (cityLower.startsWith(q)) {
      cityPrefixMatches.push(s);
    } else if (
      codeLower.includes(q) ||
      nameLower.includes(q) ||
      cityLower.includes(q) ||
      stateLower.includes(q) ||
      aliasMatch
    ) {
      otherMatches.push(s);
    }
  }

  const combined = [
    ...exactCodeMatches,
    ...codePrefixMatches,
    ...namePrefixMatches,
    ...cityPrefixMatches,
    ...otherMatches,
  ];

  return combined.slice(0, limit);
};

/**
 * Helper to get a single station by code (case-insensitive)
 */
export const getStationByCode = (code: string): StationItem | undefined => {
  if (!code) return undefined;
  const upper = code.trim().toUpperCase();
  return ALL_INDIAN_STATIONS.find((s) => s.code === upper);
};
